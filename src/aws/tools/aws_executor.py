"""
AWS Dynamic Executor
====================
Executes boto3 API calls that were generated by the LLM and approved by the user.

Used in two places:
  1. Auto-execution: when action != alert_only and confidence is high
  2. Approval flow: user approves suggested_commands → this runs them

Safety:
  - ALLOWED_OPERATIONS allowlist: only these (service, method) pairs can run
  - BLOCKED_METHODS hard-stop: these can never run regardless of allowlist
  - Each call requires a human-readable 'description' for audit trail
  - Errors stop the chain — subsequent commands are not executed
"""

from __future__ import annotations

import logging
from typing import Any

import boto3
from botocore.exceptions import ClientError

logger = logging.getLogger(__name__)

